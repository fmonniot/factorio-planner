local format = require("lib.format")

describe("format.number", function()
  it("keeps at most two decimals and drops trailing zeros", function()
    assert.are.equal("60", format.number(60))
    assert.are.equal("0.14", format.number(0.143))
    assert.are.equal("1.75", format.number(1.75))
    assert.are.equal("1.5", format.number(1.5))
    assert.are.equal("0", format.number(0))
    assert.are.equal("1234.57", format.number(1234.567))
  end)
end)

describe("format.rate", function()
  it("writes the per-minute unit", function()
    assert.are.equal("60/min", format.rate(60))
    assert.are.equal("0.5/min", format.rate(0.5))
  end)
end)

describe("format.tooltip_number", function()
  it("separates the thousands and keeps the two decimals of format.number", function()
    assert.are.equal("0", format.tooltip_number(0))
    assert.are.equal("60", format.tooltip_number(60))
    assert.are.equal("999", format.tooltip_number(999))
    assert.are.equal("1,000", format.tooltip_number(1000))
    assert.are.equal("1,234.57", format.tooltip_number(1234.567))
    assert.are.equal("1,234,567.5", format.tooltip_number(1234567.5))
    assert.are.equal("100,000", format.tooltip_number(100000))
    assert.are.equal("0.14", format.tooltip_number(0.143))
  end)
  it("keeps the sign of a negative number", function()
    assert.are.equal("-1,234.5", format.tooltip_number(-1234.5))
    assert.are.equal("-12", format.tooltip_number(-12))
  end)
end)

describe("format.reselect", function()
  local names = { "Gears", "Circuits", "Gears" }
  it("keeps the position when the block of that name is still there", function()
    assert.are.equal(3, format.reselect(names, 3, "Gears"))
    assert.are.equal(2, format.reselect(names, 2, "Circuits"))
  end)
  it("follows a block that moved, to the first of that name", function()
    assert.are.equal(2, format.reselect({ "A", "Circuits" }, 1, "Circuits"))
    assert.are.equal(1, format.reselect(names, 2, "Gears"))
  end)
  it("falls back to the first block when the name is gone", function()
    assert.are.equal(1, format.reselect(names, 2, "Plastic"))
    assert.are.equal(1, format.reselect({}, 4, "Gears"))
  end)
  it("keeps a valid index when no name was recorded", function()
    assert.are.equal(2, format.reselect(names, 2, nil))
    assert.are.equal(1, format.reselect(names, 9, nil))
  end)
end)

describe("format.machines", function()
  it("writes the rounded-up count and the exact one", function()
    assert.are.equal("2 (1.75)", format.machines(2, 1.75))
  end)
  it("copes with either missing, and with both", function()
    assert.are.equal("2", format.machines(2, nil))
    assert.are.equal("(1.75)", format.machines(nil, 1.75))
    assert.is_nil(format.machines(nil, nil))
  end)
end)

describe("format.colored", function()
  it("wraps text in a rich-text colour tag", function()
    assert.are.equal("[color=#3b82f6]x[/color]", format.colored("#3b82f6", "x"))
  end)
end)

describe("element tags", function()
  it("round-trip the keys and what the element is", function()
    for _, what in ipairs({ "check", "machine", "beacon" }) do
      local block, entry, got = format.parse_tags(format.tags("Gears", "A" .. "\31" .. "r", what))
      assert.are.equal("Gears", block)
      assert.are.equal("A" .. "\31" .. "r", entry)
      assert.are.equal(what, got)
    end
  end)
  it("lets the summary row's checkbox have no entry key, and nothing else", function()
    local block, entry, what = format.parse_tags(format.tags("Gears", nil, "check"))
    assert.are.equal("Gears", block)
    assert.is_nil(entry)
    assert.are.equal("check", what)
    assert.is_nil(format.parse_tags(format.tags("Gears", nil, "machine")))
    assert.is_nil(format.parse_tags(format.tags("Gears", nil, "beacon")))
  end)
  it("accepts an empty block name or entry key, which a nameless block can have", function()
    local block, entry = format.parse_tags(format.tags("", "", "machine"))
    assert.are.equal("", block)
    assert.are.equal("", entry)
  end)
  it("refuse anything that is not ours", function()
    assert.is_nil(format.parse_tags(nil))
    assert.is_nil(format.parse_tags("tags"))
    assert.is_nil(format.parse_tags({}))
    assert.is_nil(format.parse_tags({ block = 1, entry = "r", what = "check" }))
    assert.is_nil(format.parse_tags({ block = "B", entry = 5, what = "check" }))
    assert.is_nil(format.parse_tags({ block = "B", entry = "r", what = "close" }))
    assert.is_nil(format.parse_tags({ block = "B", entry = "r" }))
  end)
  it("names the block drop-down", function()
    assert.are.equal("fp_viewer_block_dropdown", format.BLOCK_DROPDOWN)
  end)
end)

describe("locale keys", function()
  it("localises the synthetic row kinds and passes another through", function()
    assert.are.same({ "fp-viewer.kind-mining" }, format.synthetic_kind_text("mining"))
    assert.are.equal("other", format.synthetic_kind_text("other"))
  end)
  it("names the indicator keys, and none for no indicator", function()
    assert.are.equal("fp-viewer.indicator-stale", format.indicator_key("stale"))
    assert.is_nil(format.indicator_key(nil))
    assert.is_nil(format.indicator_key("unknown"))
  end)
end)
